// Writes database/seed/products.sql from the website's own product list, so the database can be
// loaded with the real catalogue (names, panel layouts and 3D model paths) in one step.
// Usage: node scripts/generate-product-seed.mjs
import { writeFileSync } from "node:fs";
const { products } = await import("../src/data/products/index.ts");
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const rows = products.map((p, i) =>
  `  (${q(p.slug)}, ${q(p.sku)}, ${q(p.name)}, ${p.panelCount}, ${q(p.construction)}, ${q(p.material)}, ${q(p.description)}, ${q(p.model)}, ${q(p.poster)}, ${p.featured}, ${i}, true)`);
const sql = `-- Generated by scripts/generate-product-seed.mjs from src/data/products. Safe to run more than once.
-- These are the website's real football designs (names, panel counts and 3D model files); there are no prices or stock.
insert into products (slug, sku, name, panel_count, construction, material, description, model_path, poster_path, featured, sort_order, is_active) values
${rows.join(",\n")}
on conflict (slug) do update set
  name = excluded.name, panel_count = excluded.panel_count, construction = excluded.construction, material = excluded.material,
  description = excluded.description, model_path = excluded.model_path, poster_path = excluded.poster_path,
  featured = excluded.featured, sort_order = excluded.sort_order;
`;
writeFileSync("database/seed/products.sql", sql);
console.log(`Wrote ${products.length} products to database/seed/products.sql`);
